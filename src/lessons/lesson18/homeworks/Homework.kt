    washer.programAction("Хлопок")
    washer.powerOn()
    washer.programAction("Хлопок")
    washer.setTemperature(40)
    washer.setTemperature(95)
    washer.setTimer(90)
    washer.execute()
    washer.connectToWaterSupply()
    washer.connectToDrain()
    washer.execute()
    washer.getWater(40)
    washer.open()
    washer.execute()
    washer.close()
    washer.execute()
